/** 原创技能模板只描述专业交互；权限、执行器和收费由服务端控制。 */
export function skillDocumentTemplate(label:string){return `# ${label || '创作技能'}
## 适用范围
描述使用场景、目标用户与交付物。
## 所需输入与素材
说明必要信息；只引用有权使用的固定版本，未读取内容不宣称已理解。
## 澄清规则
仅询问缺失的关键信息，每轮一个问题；闲聊不强制推进生成。
## 交互步骤
理解需求 → 补充缺失信息 → 整理完整方案 → 核对真实报价 → 用户确认。
## 结构化产出要求
普通回复使用 reply；缺失信息使用 question；就绪方案使用 proposal。
proposal 的 generation_prompt 必须包含完整需求、最新修改及已回答约束，不能只有确认短句。
技术参数以用户最新明确修改、已确认参数、技能默认值为序；不能擅自更换模型。
## 工具能力与限制
只使用平台已开放能力，不执行代码、任意网址或自动收费。
## 质量检查
检查主体、风格、构图及排除项是否保留；规格必须符合真实模型能力。
## 示例
用户提出需求 → 助手补充必要信息 → 给出完整需求和规格，等待报价确认。
`}
